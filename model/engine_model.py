PRINTED = (PAWN_PRINTED, KNIGHT_PRINTED, BISHOP_PRINTED,
           ROOK_PRINTED, QUEEN_PRINTED, KING_PRINTED)


PST = tuple(tuple(table[sq ^ 56] for sq in range (64)) for table in PRINTED)
#this line does the flip , table's first printed entry is a8 not a1 XORing with 56 swaps rank 1 with 8 rank 2 with 7 and etc without changing file


def squares(bb):
    while bb:
        sq = (bb & -bb).bit_length() - 1
        yield sq
        bb &= bb - 1


def evaluate(pos):
    total = 0
    for t in range(1, 7):
        board = pos.bb[t - 1]
        for sq in squares(board & pos.bb[BB_WHITE]):
            total += VALUE[t] + PST[t-1][sq]
        for sq in squares(board & pos.bb[BB_BLACK]):
            total -= VALUE[t] + PST[t-1][sq ^ 56]
    return -total if pos.stm else total 

